function remEuclid(a, m) { var r = a % m; return r < 0 ? r + m : r; }
function hls(c) {
  var r = c[0] / 255, g = c[1] / 255, b = c[2] / 255;
  var mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2;
  if (mx === mn) return [0, l, 0];
  var s = l <= 0.5 ? (mx - mn) / (mx + mn) : (mx - mn) / (2 - mx - mn);
  var rc = (mx - r) / (mx - mn), gc = (mx - g) / (mx - mn), bc = (mx - b) / (mx - mn);
  var h = r === mx ? bc - gc : g === mx ? 2 + rc - bc : 4 + gc - rc;
  return [remEuclid(h / 6, 1), l, s];
}
function rgbOf(h, l, s) {
  h = remEuclid(h, 1); l = clamp(l, 0, 1); s = clamp(s, 0, 1);
  if (s === 0) return [l * 255, l * 255, l * 255];
  var m2 = l <= 0.5 ? l * (1 + s) : l + s - l * s;
  var m1 = 2 * l - m2;
  function v(hue) {
    hue = remEuclid(hue, 1);
    var x = hue < 1 / 6 ? m1 + (m2 - m1) * hue * 6 : hue < 0.5 ? m2 : hue < 2 / 3 ? m1 + (m2 - m1) * (2 / 3 - hue) * 6 : m1;
    return x * 255;
  }
  return [v(h + 1 / 3), v(h), v(h - 1 / 3)];
}
function hexColor(c) {
  function b(x) { var n = Math.floor(clamp(x, 0, 255)); var s = n.toString(16); return s.length < 2 ? "0" + s : s; }
  return "#" + b(c[0]) + b(c[1]) + b(c[2]);
}
function paletteFromRgb(px) {
  if (!px.length) throw new Error("empty image");
  var sorted = px.slice().sort(function(a, b) { return (a[0] + a[1] + a[2]) - (b[0] + b[1] + b[2]); });
  var k = 8;
  var cent = [];
  for (var i = 0; i < k; i++) cent.push(sorted[Math.floor((i * 2 + 1) * sorted.length / (2 * k))].slice());
  var asg = [];
  for (var iter = 0; iter < 12; iter++) {
    for (var q = 0; q < px.length; q++) {
      var best = 0, bd = Infinity;
      for (var c = 0; c < k; c++) {
        var d = (px[q][0] - cent[c][0]) * (px[q][0] - cent[c][0]) + (px[q][1] - cent[c][1]) * (px[q][1] - cent[c][1]) + (px[q][2] - cent[c][2]) * (px[q][2] - cent[c][2]);
        if (d < bd) { bd = d; best = c; }
      }
      asg[q] = best;
    }
    var sum = [], n = [];
    for (var c2 = 0; c2 < k; c2++) { sum.push([0, 0, 0]); n.push(0); }
    for (var q2 = 0; q2 < px.length; q2++) {
      var cc = asg[q2]; n[cc]++; sum[cc][0] += px[q2][0]; sum[cc][1] += px[q2][1]; sum[cc][2] += px[q2][2];
    }
    for (var c3 = 0; c3 < k; c3++) if (n[c3]) { cent[c3][0] = sum[c3][0] / n[c3]; cent[c3][1] = sum[c3][1] / n[c3]; cent[c3][2] = sum[c3][2] / n[c3]; }
  }
  var counts = [];
  for (var z = 0; z < k; z++) counts.push(0);
  for (var a = 0; a < asg.length; a++) counts[asg[a]]++;
  var cols = [];
  for (var c4 = 0; c4 < k; c4++) if (counts[c4]) cols.push([counts[c4], cent[c4]]);
  cols.sort(function(a, b) { return b[0] - a[0]; });
  var tot = 0;
  for (var t = 0; t < cols.length; t++) tot += cols[t][0];
  var lum = 0;
  for (var u = 0; u < cols.length; u++) lum += cols[u][0] * (0.299 * cols[u][1][0] + 0.587 * cols[u][1][1] + 0.114 * cols[u][1][2]);
  lum = lum / tot / 255;
  var light = lum > 0.55;
  var dom = hls(cols[0][1]);
  var n0 = cols[0][0];
  var acc = cols[0][1], accScore = -1;
  for (var s = 0; s < cols.length; s++) {
    var sc = hls(cols[s][1])[2] * (0.3 + Math.min(cols[s][0] / n0, 1));
    if (sc >= accScore) { accScore = sc; acc = cols[s][1]; }
  }
  var ah = hls(acc);
  var ds = Math.min(dom[2], 0.25);
  function pick(a, b) { return light ? a : b; }
  var lv = pick(0.38, 0.68);
  var sat = clamp(ah[2], 0.45, 0.75);
  var rows = [
    ["accent", hexColor(rgbOf(ah[0], lv, sat))],
    ["selection", hexColor(rgbOf(ah[0], pick(0.82, 0.28), sat * 0.6))],
    ["muted", hexColor(rgbOf(dom[0], pick(0.55, 0.5), 0.08))],
    ["", ""],
    ["background", hexColor(rgbOf(dom[0], pick(0.96, 0.09), ds))],
    ["dark_background", hexColor(rgbOf(dom[0], pick(0.93, 0.07), ds))],
    ["darker_background", hexColor(rgbOf(dom[0], pick(0.89, 0.05), ds))],
    ["lighter_background", hexColor(rgbOf(dom[0], pick(0.80, 0.16), ds))],
    ["", ""],
    ["foreground", hexColor(rgbOf(dom[0], pick(0.12, 0.90), 0.12))],
    ["dark_foreground", hexColor(rgbOf(dom[0], pick(0.75, 0.6), 0.1))],
    ["light_foreground", hexColor(rgbOf(dom[0], pick(0.12, 0.90), 0.12))],
    ["bright_foreground", hexColor(rgbOf(dom[0], pick(0.0, 1.0), 0.0))],
    ["", ""]
  ];
  var hues = [["red", 0], ["yellow", 0.13], ["green", 0.33], ["cyan", 0.5], ["blue", 0.6], ["magenta", 0.83]];
  function adj(h) { return Math.abs(h - ah[0]) < 0.15 ? h * 0.85 + ah[0] * 0.15 : h; }
  for (var hi = 0; hi < hues.length; hi++) rows.push([hues[hi][0], hexColor(rgbOf(adj(hues[hi][1]), lv, sat))]);
  rows.push(["", ""]);
  for (var hj = 0; hj < hues.length; hj++) rows.push(["bright_" + hues[hj][0], hexColor(rgbOf(adj(hues[hj][1]), lv + pick(-0.08, 0.1), sat))]);
  var out = "mode = \"" + (light ? "light" : "dark") + "\"\n\n";
  for (var r = 0; r < rows.length; r++) out += rows[r][0] ? rows[r][0] + " = \"" + rows[r][1] + "\"\n" : "\n";
  return out;
}
function paletteFromBytes(bytes) {
  var im = decodePngBytes(bytes);
  var thumb = im;
  if (im.width > 256 || im.height > 256) {
    var scale = Math.max(im.width, im.height) / 256;
    var nw = Math.max(1, Math.round(im.width / scale));
    var nh = Math.max(1, Math.round(im.height / scale));
    var rgb = [];
    for (var y = 0; y < nh; y++) {
      var sy = Math.min(im.height - 1, Math.floor(y * im.height / nh));
      for (var x = 0; x < nw; x++) {
        var sx = Math.min(im.width - 1, Math.floor(x * im.width / nw));
        rgb.push(im.rgb[sy * im.width + sx]);
      }
    }
    thumb = { rgb: rgb };
  }
  return paletteFromRgb(thumb.rgb);
}

function Inflator(data, pos) { this.d = data; this.p = pos || 0; this.buf = 0; this.cnt = 0; }
Inflator.prototype.bits = function(n) {
  while (this.cnt < n) {
    if (this.p >= this.d.length) throw new Error("truncated");
    this.buf |= this.d[this.p++] << this.cnt;
    this.cnt += 8;
  }
  var v = this.buf & ((1 << n) - 1);
  this.buf >>>= n;
  this.cnt -= n;
  return v;
};
Inflator.prototype.align = function() { this.buf = 0; this.cnt = 0; };
function huffmanTree(lengths) {
  var max = 0, i;
  for (i = 0; i < lengths.length; i++) if (lengths[i] > max) max = lengths[i];
  var count = [];
  for (i = 0; i <= max; i++) count[i] = 0;
  for (i = 0; i < lengths.length; i++) if (lengths[i]) count[lengths[i]]++;
  var next = [], code = 0;
  for (var bits = 1; bits <= max; bits++) { code = (code + count[bits - 1]) << 1; next[bits] = code; }
  var root = {};
  for (var sym = 0; sym < lengths.length; sym++) {
    var len = lengths[sym];
    if (!len) continue;
    var c = next[len]++;
    var node = root;
    for (var b = len - 1; b >= 0; b--) {
      var bit = (c >> b) & 1;
      if (b === 0) node[bit] = sym;
      else {
        if (typeof node[bit] !== "object") node[bit] = {};
        node = node[bit];
      }
    }
  }
  return root;
}
function readSym(inf, tree) {
  var node = tree;
  while (typeof node === "object") node = node[inf.bits(1)];
  if (typeof node !== "number") throw new Error("bad code");
  return node;
}
function fixedLit() {
  var L = [];
  for (var i = 0; i <= 143; i++) L[i] = 8;
  for (var j = 144; j <= 255; j++) L[j] = 9;
  for (var k = 256; k <= 279; k++) L[k] = 7;
  for (var n = 280; n <= 287; n++) L[n] = 8;
  return huffmanTree(L);
}
function fixedDist() {
  var L = [];
  for (var i = 0; i < 30; i++) L[i] = 5;
  return huffmanTree(L);
}
function inflateRaw(data, pos) {
  var inf = new Inflator(data, pos);
  var out = [];
  var bfinal = 0;
  var fixedL = null, fixedD = null;
  do {
    bfinal = inf.bits(1);
    var btype = inf.bits(2);
    if (btype === 0) {
      inf.align();
      if (inf.p + 4 > inf.d.length) throw new Error("truncated stored");
      var len = inf.d[inf.p] | (inf.d[inf.p + 1] << 8);
      inf.p += 4;
      for (var i = 0; i < len; i++) out.push(inf.d[inf.p++]);
    } else if (btype === 1 || btype === 2) {
      var lit, dist;
      if (btype === 1) {
        if (!fixedL) { fixedL = fixedLit(); fixedD = fixedDist(); }
        lit = fixedL; dist = fixedD;
      } else {
        var nlit = inf.bits(5) + 257, ndist = inf.bits(5) + 1, nlen = inf.bits(4) + 4;
        var clen = [];
        for (var c = 0; c < 19; c++) clen[c] = 0;
        for (var n = 0; n < nlen; n++) clen[CLEN_ORDER[n]] = inf.bits(3);
        var clTree = huffmanTree(clen);
        var lengths = [];
        while (lengths.length < nlit + ndist) {
          var sym = readSym(inf, clTree);
          if (sym < 16) lengths.push(sym);
          else if (sym === 16) { var rep = inf.bits(2) + 3, prev = lengths[lengths.length - 1]; for (var r = 0; r < rep; r++) lengths.push(prev); }
          else if (sym === 17) { var z = inf.bits(3) + 3; for (var r2 = 0; r2 < z; r2++) lengths.push(0); }
          else { var z2 = inf.bits(7) + 11; for (var r3 = 0; r3 < z2; r3++) lengths.push(0); }
        }
        lit = huffmanTree(lengths.slice(0, nlit));
        dist = huffmanTree(lengths.slice(nlit, nlit + ndist));
      }
      while (true) {
        var s = readSym(inf, lit);
        if (s < 256) out.push(s);
        else if (s === 256) break;
        else {
          var li = s - 257;
          var length = LEN_BASE[li] + (LEN_EXTRA[li] ? inf.bits(LEN_EXTRA[li]) : 0);
          var di = readSym(inf, dist);
          var distance = DIST_BASE[di] + (DIST_EXTRA[di] ? inf.bits(DIST_EXTRA[di]) : 0);
          for (var k = 0; k < length; k++) out.push(out[out.length - distance]);
        }
      }
    } else throw new Error("bad block");
  } while (!bfinal);
  return out;
}
function inflateZlib(bytes) {
  if (bytes.length < 6) throw new Error("short zlib");
  var cmf = bytes[0], flg = bytes[1];
  if ((cmf & 15) !== 8) throw new Error("not deflate");
  if (((cmf << 8) + flg) % 31 !== 0) throw new Error("bad zlib header");
  var pos = 2;
  if (flg & 32) pos += 4;
  return inflateRaw(bytes, pos);
}
function paeth(a, b, c) {
  var p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
  if (pa <= pb && pa <= pc) return a;
  if (pb <= pc) return b;
  return c;
}
function unfilter(data, w, h, bpp) {
  var stride = w * bpp;
  var out = [];
  var i = 0;
  for (var y = 0; y < h; y++) {
    var filter = data[i++];
    for (var x = 0; x < stride; x++) {
      var raw = data[i++];
      var left = x >= bpp ? out[out.length - bpp] : 0;
      var up = y > 0 ? out[out.length - stride] : 0;
      var ul = y > 0 && x >= bpp ? out[out.length - stride - bpp] : 0;
      var val = raw;
      if (filter === 1) val = (raw + left) & 255;
      else if (filter === 2) val = (raw + up) & 255;
      else if (filter === 3) val = (raw + ((left + up) >> 1)) & 255;
      else if (filter === 4) val = (raw + paeth(left, up, ul)) & 255;
      else if (filter !== 0) throw new Error("bad filter");
      out.push(val);
    }
  }
  return out;
}
function u32(bytes, p) { return ((bytes[p] << 24) | (bytes[p + 1] << 16) | (bytes[p + 2] << 8) | bytes[p + 3]) >>> 0; }
function decodePngBytes(bytes) {
  var sig = [137, 80, 78, 71, 13, 10, 26, 10];
  for (var i = 0; i < 8; i++) if (bytes[i] !== sig[i]) throw new Error("not png");
  var p = 8, width = 0, height = 0, bitDepth = 0, colorType = -1, interlace = 0;
  var idat = [];
  while (p + 8 <= bytes.length) {
    var len = u32(bytes, p); p += 4;
    var type = String.fromCharCode(bytes[p], bytes[p + 1], bytes[p + 2], bytes[p + 3]); p += 4;
    if (type === "IHDR") {
      width = u32(bytes, p); height = u32(bytes, p + 4);
      bitDepth = bytes[p + 8]; colorType = bytes[p + 9]; interlace = bytes[p + 12];
    } else if (type === "IDAT") {
      for (var j = 0; j < len; j++) idat.push(bytes[p + j]);
    } else if (type === "IEND") break;
    p += len + 4;
  }
  if (bitDepth !== 8 || interlace) throw new Error("unsupported png");
  if (colorType !== 2 && colorType !== 6) throw new Error("unsupported color");
  var raw = inflateZlib(idat);
  var bpp = colorType === 6 ? 4 : 3;
  var pix = unfilter(raw, width, height, bpp);
  var rgb = [];
  for (var y = 0; y < height; y++) for (var x = 0; x < width; x++) {
    var o = (y * width + x) * bpp;
    rgb.push([pix[o], pix[o + 1], pix[o + 2]]);
  }
  return { width: width, height: height, rgb: rgb };
}

