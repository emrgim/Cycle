function cleanFull(t) {
  var s = "";
  for (var i = 0; i < t.length; i++) {
    var code = t.charCodeAt(i);
    var c = t.charAt(i);
    if (code < 32 || code === 127) continue;
    if (c === "{" || c === "}" || c === "`" || c === "$" || c === "\\") continue;
    s += c;
  }
  s = s.trim().replace(/\s+-\s+[^-]+$/, "").replace(/"/g, "'");
  s = s.replace(/^[A-Z]{2,6}\s*:\s*/, "");
  return s.trim();
}
function trim60(t) {
  var chars = Array.from(t);
  if (chars.length <= 60) return t;
  var cut = chars.slice(0, 60).join("");
  var i = cut.lastIndexOf(" ");
  if (i < 0) return cut + "\u2026";
  return cut.slice(0, i).replace(/[,:;\- ]+$/, "") + "\u2026";
}
