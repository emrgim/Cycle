function sunPosTz(when, lat, lon, tz) {
  var PI = Math.PI;
  var doy = ordinal(when.y, when.mo, when.d);
  var hr = when.h + when.mi / 60 + (when.s || 0) / 3600;
  var g = 2 * PI / 365 * (doy - 1 + (hr - 12) / 24);
  var eqt = 229.18 * (0.000075 + 0.001868 * Math.cos(g) - 0.032077 * Math.sin(g) - 0.014615 * Math.cos(2 * g) - 0.040849 * Math.sin(2 * g));
  var decl = 0.006918 - 0.399912 * Math.cos(g) + 0.070257 * Math.sin(g) - 0.006758 * Math.cos(2 * g) + 0.000907 * Math.sin(2 * g) - 0.002697 * Math.cos(3 * g) + 0.00148 * Math.sin(3 * g);
  var tst = hr * 60 + eqt + 4 * lon - 60 * tz;
  var had = tst / 4 - 180;
  var ha = had * PI / 180;
  var la = lat * PI / 180;
  var cz = clamp(Math.sin(la) * Math.sin(decl) + Math.cos(la) * Math.cos(decl) * Math.cos(ha), -1, 1);
  var zen = Math.acos(cz);
  var th = Math.acos(clamp((Math.sin(la) * cz - Math.sin(decl)) / (Math.cos(la) * Math.max(Math.sin(zen), 1e-9)), -1, 1)) * 180 / PI;
  var az = had > 0 ? (th + 180) % 360 : (540 - th) % 360;
  return [90 - zen * 180 / PI, az];
}
function sunEventsAt(day, la, lo, tz) {
  var el = [];
  var base = { y: day.y, mo: day.mo, d: day.d, h: 0, mi: 0, s: 0 };
  for (var m = 0; m <= 1440; m++) el.push(sunPosTz(dateAddMinutes(base, m), la, lo, tz)[0]);
  var noon = 0;
  for (var i = 1; i <= 1440; i++) if (el[i] >= el[noon]) noon = i;
  function hm(min) { return pad(Math.floor(min / 60) % 24, 2) + ":" + pad(min % 60, 2); }
  function up(th) {
    for (var m = 1; m <= noon; m++) if (el[m - 1] < th && el[m] >= th) return hm(m);
    return null;
  }
  function down(th) {
    for (var m = noon + 1; m <= 1440; m++) if (el[m - 1] >= th && el[m] < th) return hm(m);
    return null;
  }
  return {
    sunrise: up(-0.833), solar_noon: hm(noon), sunset: down(-0.833),
    civil_dawn: up(-6), civil_dusk: down(-6), nautical_dusk: down(-12), astronomical_dusk: down(-18)
  };
}
