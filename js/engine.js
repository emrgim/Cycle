function slotSize(every) {
  if (every === 15 || every === 30 || every === 60 || every === 120 || every === 180) return every;
  return 60;
}
function nextMark(now, every, done, inWindow) {
  var e = slotSize(every);
  var t = { y: now.y, mo: now.mo, d: now.d, h: now.h, mi: now.mi, s: 0 };
  var m = t.h * 60 + t.mi;
  if (m % e !== 0) t = dateAddMinutes(t, e - (m % e));
  var limit = Math.floor(3 * 1440 / e) + 2;
  for (var i = 0; i < limit; i++) {
    if (!dateEq(t, done) && inWindow(t)) return { y: t.y, mo: t.mo, d: t.d, h: t.h, mi: t.mi, s: 0 };
    t = dateAddMinutes(t, e);
  }
  return null;
}
function leadSecsFrom(d, every) {
  var base;
  if (!d || !d.length) base = 180;
  else {
    var v = d.slice().sort(function(a, b) { return a - b; });
    base = v[Math.round((v.length - 1) * 0.75)];
  }
  return Math.max(0, Math.min(base + 30, slotSize(every) * 60 - 60));
}
function schedPath() { return join(stateDir(), "schedules.json"); }
function lockPath() { return join(stateDir(), "generate.lock"); }
async function runningPid() {
  var t = await host.readFile(lockPath());
  if (t == null) return null;
  var pid = parseInt(String(t).trim(), 10);
  if (!pid) return null;
  if (host.pidAlive && await host.pidAlive(pid)) return pid;
  return null;
}
async function selfPid() {
  if (host.pid) return host.pid;
  if (host.selfPid) {
    var n = await host.selfPid();
    if (n) host.pid = n;
  }
  return host.pid || 0;
}
async function lockAcquire() {
  await host.mkdirp(stateDir());
  if (await runningPid()) return false;
  var pid = String(await selfPid());
  if (await host.createNew(lockPath(), pid)) return true;
  if (!(await runningPid())) {
    await host.removeFile(lockPath());
    return host.createNew(lockPath(), pid);
  }
  return false;
}
async function lockRelease() { await host.removeFile(lockPath()); }
