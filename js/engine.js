function specOf(name) {
  if (name === "weather" || name === "air" || name === "sun" || name === "sunrise" || name === "sunset" || name === "dawn" || name === "dusk" || name === "solar_noon") return WX_SPEC;
  if (name === "location") return LOC_SPEC;
  if (name === "news") return NEWS_SPEC;
  if (name === "breaking" || name === "phase" || name === "time" || name === "date" || name === "now" || name === "today" || name === "tomorrow" || name === "yesterday" || name === "style" || name === "location_full") return NONE_SPEC;
  var im = /^image([0-9]+)$/.exec(name);
  if (im && String(parseInt(im[1], 10)) === String(Number(im[1]))) return NONE_SPEC;
  if (im) return NONE_SPEC;
  return null;
}
function parseCalls(text) {
  var re = /(?:^|[\s(\[,;:"'])(\/([a-z][a-z0-9_]*)((?:\/[A-Za-z0-9_+%-]+)*))|\{\{\s*([a-z][a-z0-9_]*)\s*\}\}/g;
  var out = [];
  var m;
  while ((m = re.exec(text))) {
    if (m[1]) {
      var start = m.index + (m[0].charAt(0) === "/" ? 0 : 1);
      var args = [];
      if (m[3]) {
        var parts = m[3].split("/");
        for (var i = 0; i < parts.length; i++) if (parts[i]) args.push(parts[i]);
      }
      out.push({ name: m[2], args: args, start: start, end: start + m[1].length });
    } else {
      out.push({ name: m[4], args: [], start: m.index, end: m.index + m[0].length });
    }
  }
  return out;
}
function validateCall(c, images) {
  var sp = specOf(c.name);
  if (!sp) return { ok: false, error: "unknown command /" + c.name };
  var im = /^image([0-9]+)$/.exec(c.name);
  if (im) {
    var n = parseInt(im[1], 10);
    if (!n || n > images) return { ok: false, error: "/" + c.name + ": no reference image " + n + " in settings.images" };
  }
  var o = { city: null, query: null, day: 0 };
  var i = 0;
  while (i < c.args.length) {
    var a = c.args[i];
    var known = false;
    for (var k = 0; k < sp.length; k++) if (sp[k] === a) known = true;
    if (!known) return { ok: false, error: "/" + c.name + ": invalid argument '" + a + "' (accepted: " + (sp.length ? sp.join(", ") : "none") + ")" };
    if (a === "city" || a === "query") {
      if (i + 1 >= c.args.length) return { ok: false, error: "/" + c.name + ": '" + a + "' needs a value, e.g. /" + c.name + "/" + a + "/Genova" };
      var v = c.args[i + 1].replace(/[_+]/g, " ").replace(/%20/g, " ");
      if (a === "city") o.city = v; else o.query = v;
      i += 2;
    } else {
      o.day = a === "tomorrow" ? 1 : (a === "yesterday" ? -1 : 0);
      i += 1;
    }
  }
  return { ok: true, opts: o };
}
