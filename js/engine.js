  if (c.name === "yesterday") return fmtDay(addDays(nowDt(), -1));
  if (c.name === "now") return fmtDay(nowDt()) + ", " + fmtHm(nowDt());
  if (plain) {
    var b = baseVal();
    if (b == null) throw new Error("/" + c.name + " has no value");
    return b;
  }
