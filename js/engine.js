function windowOk(sc, when, s) {
  if (sc.window === "always") return true;
  var ev = sunEvents(when, s);
  function mm(k) {
    if (typeof ev[k] !== "string") return null;
    var p = ev[k].split(":");
    return (parseInt(p[0], 10) || 0) * 60 + (parseInt(p[1], 10) || 0);
  }
  var a = mm("civil_dawn"), b = mm("civil_dusk");
  var cur = when.h * 60 + when.mi;
  if (a == null || b == null) return true;
  return a <= cur && cur < b;
}
async function durationsOf(name) {
  var st = await schedState();
  var d = st[name] && st[name].durations;
  if (!Array.isArray(d)) return [];
  var out = [];
  for (var i = 0; i < d.length; i++) if (typeof d[i] === "number") out.push(d[i]);
  return out;
}
async function leadSecs(name, sc) {
  if (!sc.anticipate) return 0;
  return leadSecsFrom(await durationsOf(name), typeof sc.every_min === "number" ? sc.every_min : 60);
}
async function recordRun(name, markT, secs, ok) {
  var st = await schedState();
  if (!st[name]) st[name] = {};
  var e = st[name];
  if (ok && secs > 0) {
    var d = Array.isArray(e.durations) ? e.durations.slice() : [];
    d.push(secs);
    e.durations = d.slice(Math.max(0, d.length - 20));
  }
  var runs = Array.isArray(e.runs) ? e.runs.slice() : [];
  var late = false;
  if (markT) {
    var limit = dateAddMinutes(markT, 0);
    limit.s = 5;
    late = dateDiffMs(nowDt(), limit) > 0;
  }
  runs.push({ at: fmtIso(nowDt()), mark: markT ? fmtHm(markT) : null, secs: secs, ok: ok, late: late });
  e.runs = runs.slice(Math.max(0, runs.length - 10));
  await wr(schedPath(), st);
}
async function doneMark(name) {
  var st = await schedState();
  var s = st[name] && st[name].last_slot;
  return s ? parseIso(s) : null;
}
async function nextRun(name, sc, s) {
  if (!sc.enabled) return null;
  return nextMark(nowDt(), typeof sc.every_min === "number" ? sc.every_min : 60, await doneMark(name), function(t) { return windowOk(sc, t, s); });
}
