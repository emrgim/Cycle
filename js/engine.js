function ruleMatch(expr, w) {
  var e = String(expr || "").trim();
  if (/^\w+$/.test(e)) {
    var v = w ? w[e] : undefined;
    if (v === true) return true;
    if (v === false || v == null) return false;
    if (typeof v === "number") return v !== 0;
    if (typeof v === "string") return v.length > 0;
    return false;
  }
  var m = /^(\w+)\s*(>=|<=|>|<|==)\s*(-?[\d.]+)$/.exec(e);
  if (!m || !w || typeof w[m[1]] !== "number") return false;
  var a = w[m[1]], b = parseFloat(m[3]);
  if (m[2] === ">=") return a >= b;
  if (m[2] === "<=") return a <= b;
  if (m[2] === ">") return a > b;
  if (m[2] === "<") return a < b;
  return a === b;
}
