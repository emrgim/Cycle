async function learn(slot, now) {
  var logv = (await rd(overridesPath())) || [];
  if (!Array.isArray(logv)) logv = [];
  var per = [];
  for (var i = logv.length - 1; i >= 0; i--) {
    var o = logv[i];
    if (!o || o.slot !== slot) continue;
    var day = String(o.at || "").slice(0, 10);
    if (!day) continue;
    var seen = false;
    for (var j = 0; j < per.length; j++) if (per[j][0] === day) seen = true;
    if (seen) continue;
    per.push([day, typeof o.base === "number" ? o.base : 0, typeof o.user === "number" ? o.user : 0]);
    if (per.length >= RECENT_DAYS) break;
  }
  var up = [], down = [];
  for (var u = 0; u < per.length; u++) {
    if (per[u][2] > per[u][1]) up.push(per[u]);
    else if (per[u][2] < per[u][1]) down.push(per[u]);
  }
  var dirName, pick;
  if (up.length >= MIN_DAYS && up.length >= down.length) { dirName = "up"; pick = up; }
  else if (down.length >= MIN_DAYS) { dirName = "down"; pick = down; }
  else return null;
  var users = [];
  var bases = [];
  var days = [];
  for (var p = 0; p < pick.length; p++) { days.push(pick[p][0]); bases.push(pick[p][1]); users.push(pick[p][2]); }
  var target = clamp(median(users), 1, 100);
  var prof = (await rd(profilePath())) || {};
  if (!prof || typeof prof !== "object" || Array.isArray(prof)) prof = {};
  if (!prof.slots) prof.slots = {};
  var prev = prof.slots[slot] || {};
  var current = typeof prev.current === "number" ? prev.current : median(bases);
  var entry = { target: target, current: current, direction: dirName, days: days, user_values: users, last_step_day: prev.last_step_day == null ? null : prev.last_step_day, updated: fmtIso(now) };
  prof.note = "Learned brightness base per Cycle slot. current walks to target by at most 5 points a day. Reset with: cycle reset-profile";
  prof.slots[slot] = entry;
  await wr(profilePath(), prof);
  return entry;
}
