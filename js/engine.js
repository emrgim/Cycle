  if (c.name === "air") return airFor(s, o);
  if (c.name === "sun") return sunFor(s, o);
  if (c.name === "dawn") return eventFor(s, o, "civil_dawn");
  if (c.name === "dusk") return eventFor(s, o, "civil_dusk");
  if (c.name === "sunrise" || c.name === "sunset" || c.name === "solar_noon") return eventFor(s, o, c.name);
