//! Prompt titles and the Omarchy launcher submenu "Cycle Prompts" (static JSONC rows kept in sync,
//! because the Omarchy shell only runs its own built-in providers).
use crate::core::{self, home, settings, update_settings};
use serde_json::json;
use std::fs;

pub fn title(id: &str) -> String {
    if let Some(t) = settings()["prompt_titles"][id].as_str().filter(|t| !t.trim().is_empty()) { return t.to_string(); }
    id.split(['-', '_']).filter(|w| !w.is_empty()).map(|w| { let mut c = w.chars(); c.next().map(|f| f.to_uppercase().collect::<String>() + c.as_str()).unwrap_or_default() }).collect::<Vec<_>>().join(" ")
}
pub fn set_title(id: &str, t: &str) { let t = t.trim().to_string(); update_settings(|s| { if !s["prompt_titles"].is_object() { s["prompt_titles"] = json!({}); } s["prompt_titles"][id] = json!(t); }); }

const BEGIN: &str = "  // BEGIN cycle prompts (generated by `cycle prompts sync-menu`)";
const END: &str = "  // END cycle prompts";
fn q(s: &str) -> String { serde_json::to_string(s).unwrap() }

/// Rewrite the generated block in ~/.config/omarchy/extensions/omarchy-menu.jsonc.
pub fn sync() {
    let f = home().join(".config/omarchy/extensions/omarchy-menu.jsonc");
    let Ok(txt) = fs::read_to_string(&f) else { return };
    let exe = home().join(".local/bin/cycle").to_string_lossy().to_string();
    let mut block = vec![BEGIN.to_string()];
    for id in core::prompt_names() {
        let k = format!("cycle.update.{}", id.replace('.', "-"));
        let t = title(&id);
        let active = if id == core::active_prompt() { " ✓" } else { "" };
        block.push(format!("  {}: {{\"icon\":\"󰏪\",\"label\":{}}},", q(&k), q(&format!("{t}{active}"))));
        block.push(format!("  {}: {{\"icon\":\"󰖐\",\"label\":\"Generate\",\"description\":\"Generate and apply a wallpaper from this prompt with live data\",\"action\":{}}},", q(&format!("{k}.generate")),
            q(&format!("setsid -f {exe} generate --prompt {} >/dev/null 2>&1; omarchy-notification-send -u low {}", core::quote(&id), core::quote(&format!("Cycle: generating “{t}” from live data"))))));
        block.push(format!("  {}: {{\"icon\":\"󰏫\",\"label\":\"Edit\",\"action\":{}}},", q(&format!("{k}.edit")), q(&format!("setsid -f uwsm-app -- {exe} open --prompt {} >/dev/null 2>&1", core::quote(&id)))));
    }
    block.push(END.to_string());
    let mut lines: Vec<String> = Vec::new(); let mut skip = false;
    for l in txt.lines() {
        if l.starts_with(BEGIN) { skip = true; continue; }
        if skip { if l.starts_with(END) { skip = false; } continue; }
        lines.push(l.to_string());
    }
    // insert just before the "cycle.open" row
    let at = lines.iter().position(|l| l.contains("\"cycle.open\"")).unwrap_or(lines.len().saturating_sub(1));
    for (i, b) in block.into_iter().enumerate() { lines.insert(at + i, b); }
    let out = lines.join("\n") + "\n";
    if out != txt { let tmp = f.with_extension("jsonc.tmp"); if fs::write(&tmp, &out).is_ok() { let _ = fs::rename(&tmp, &f); } }
}
